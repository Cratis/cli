using System.Reflection;
using Cratis.Chronicle.Connections;
using Cratis.Chronicle.XUnit.Integration;
using DotNet.Testcontainers.Builders;
using DotNet.Testcontainers.Containers;
using DotNet.Testcontainers.Networks;

namespace Cratis.Cli.Integration.Chronicle;

/// <summary>
/// Adapts Chronicle's published xUnit v3 harness for the CLI's external connections and isolated configuration.
/// </summary>
public class CliChronicleFixture : ChronicleOutOfProcessFixture, IAsyncLifetime
{
    const string CertificatePassword = "TestPassword123";

    readonly string _testHome = Path.Combine(Path.GetTempPath(), $"cratis-cli-integration-{Guid.NewGuid():N}");
    string? _previousHome;
    string? _previousUserProfile;
    string? _previousXdgConfigHome;
    string? _previousUpdateCheck;
    bool _environmentIsolated;

    /// <summary>
    /// Gets the path to the test certificate file on the host, generated by the published harness.
    /// </summary>
    public static string CertificatePath { get; } = TestCertificateGenerator.GenerateAndSaveCertificate(
        Path.Combine(Path.GetTempPath(), "chronicle-cli-test-certs", "chronicle-test.pfx"), CertificatePassword);

    static string BackupsPath => Path.Combine(AppContext.BaseDirectory, "backups");

    /// <summary>
    /// Gets the Chronicle image: the override, else the image named after the Chronicle package version that CI pulls before the run.
    /// </summary>
    static string ChronicleImageName => Environment.GetEnvironmentVariable("CRATIS_CHRONICLE_LOCAL_IMAGE") ?? PackageVersionImageName();

    /// <inheritdoc/>
    public async ValueTask InitializeAsync()
    {
        _previousHome = Environment.GetEnvironmentVariable("HOME");
        _previousUserProfile = Environment.GetEnvironmentVariable("USERPROFILE");
        _previousXdgConfigHome = Environment.GetEnvironmentVariable("XDG_CONFIG_HOME");
        _previousUpdateCheck = Environment.GetEnvironmentVariable("CRATIS_NO_UPDATE_CHECK");
        Directory.CreateDirectory(_testHome);
        _environmentIsolated = true;
        Environment.SetEnvironmentVariable("HOME", _testHome);
        Environment.SetEnvironmentVariable("USERPROFILE", _testHome);
        Environment.SetEnvironmentVariable("XDG_CONFIG_HOME", _testHome);
        Environment.SetEnvironmentVariable("CRATIS_NO_UPDATE_CHECK", "1");

        try
        {
            // Fail before running the CLI if it does not resolve configuration inside the isolated home.
            var expectedPath = Path.Combine(_testHome, ".cratis", "config.json");
            if (!string.Equals(CliConfiguration.GetConfigPath(), expectedPath, OperatingSystem.IsWindows() ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal))
            {
                throw new InvalidOperationException("The integration CLI configuration path is outside the isolated test home.");
            }

            await DevClientCredentials.Ensure(MongoDBPort);
        }
        catch
        {
            RestoreEnvironment();
            Directory.Delete(_testHome, true);
            _environmentIsolated = false;
            throw;
        }
    }

    /// <inheritdoc/>
    public override async ValueTask DisposeAsync()
    {
        try
        {
            await base.DisposeAsync();
        }
        finally
        {
            if (_environmentIsolated)
            {
                RestoreEnvironment();
                Directory.Delete(_testHome, true);
            }
        }
    }

    /// <inheritdoc/>
    protected override IContainer BuildContainer(INetwork network)
    {
        Directory.CreateDirectory(BackupsPath);

        // Keep the CLI's two-minute HTTPS readiness deadline and fixed external connection ports.
        var waitStrategy = Wait.ForUnixContainer()
            .AddCustomWaitStrategy(new HttpsHealthWait(35000), strategy => strategy.WithTimeout(TimeSpan.FromMinutes(2)));
        var builder = ConfigureImage(new ContainerBuilder(ChronicleImageName))
            .WithEnvironment("Storage__ConnectionDetails", "mongodb://localhost:27017")
            .WithPortBinding(MongoDBPort, 27017)
            .WithPortBinding(35001, 35000)
            .WithHostname(HostName)
            .WithBindMount(BackupsPath, "/backups")
            .WithNetwork(network)
            .WithWaitStrategy(waitStrategy);

        return WithReservedKernelPorts(builder).Build();
    }

    /// <inheritdoc/>
    protected override ContainerBuilder ConfigureImage(ContainerBuilder builder) =>
        builder
            .WithImage(ChronicleImageName)
            .WithBindMount(CertificatePath, "/app/certs/chronicle.pfx")
            .WithEnvironment("Cratis__Chronicle__Tls__CertificatePath", "/app/certs/chronicle.pfx")
            .WithEnvironment("Cratis__Chronicle__Tls__CertificatePassword", CertificatePassword)
            .WithEnvironment("Cratis__Chronicle__EncryptionCertificate__CertificatePath", "/app/certs/chronicle.pfx")
            .WithEnvironment("Cratis__Chronicle__EncryptionCertificate__CertificatePassword", CertificatePassword);

    static string PackageVersionImageName()
    {
        var version = typeof(ChronicleConnectionString).Assembly
            .GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion ?? "latest";
        var plusIndex = version.IndexOf('+');
        if (plusIndex >= 0) version = version[..plusIndex];
        return $"cratis/chronicle:{version}-development";
    }

    void RestoreEnvironment()
    {
        Environment.SetEnvironmentVariable("HOME", _previousHome);
        Environment.SetEnvironmentVariable("USERPROFILE", _previousUserProfile);
        Environment.SetEnvironmentVariable("XDG_CONFIG_HOME", _previousXdgConfigHome);
        Environment.SetEnvironmentVariable("CRATIS_NO_UPDATE_CHECK", _previousUpdateCheck);
    }
}
